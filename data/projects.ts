export const PROJECTS: Project[] = RAW_PROJECTS.map((p) =>
  p.slug in VIDEO_START
    ? { ...p, video: `/videos/${p.slug}.webm`, videoStart: VIDEO_START[p.slug], videoPortrait: PORTRAIT.has(p.slug) }
    : p,
);

export const FEATURED_PROJECTS = PROJECTS.filter((p) => p.featured);

export function getProject(slug: string) {
  return PROJECTS.find((p) => p.slug === slug);
}

export function getAdjacentProject(slug: string) {
  const i = PROJECTS.findIndex((p) => p.slug === slug);
  return PROJECTS[(i + 1) % PROJECTS.length];
}

export function projectsIn(category: ProjectCategory | "All") {
  return category === "All" ? PROJECTS : PROJECTS.filter((p) => p.categories.includes(category));
}
